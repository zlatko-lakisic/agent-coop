"""Write the wiki pages that must match the program."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PHRASES = ROOT / "src" / "agentcoop" / "data" / "phrases.json"
GENERATED = "<!-- Generated by scripts/gen_wiki.py. Do not edit by hand. -->"

TEMPLATE_FILES = {
    "skill": ("src/agentcoop/templates/SKILL.md.tmpl",),
    "rule": ("src/agentcoop/templates/cursor-rule.mdc.tmpl",),
    "agents": ("src/agentcoop/templates/AGENTS.md.tmpl",),
    "gemini": ("src/agentcoop/templates/GEMINI.md.tmpl",),
    "board": ("src/agentcoop/templates/board-README.md.tmpl",),
    "desktop": (
        "skills/agent-coop/SKILL.md",
        "src/agentcoop/data/agent-coop/SKILL.md",
    ),
}

PAGES = ("Chat-phrases.md", "Command-reference.md")


def load_phrases(path: Path | None = None) -> dict:
    """Return the phrase list."""
    raw = json.loads((path or PHRASES).read_text(encoding="utf-8"))
    if not isinstance(raw, dict) or not isinstance(raw.get("groups"), list):
        raise SystemExit("phrases.json must be an object with a groups list.")
    return raw


def phrase_files(row: dict, key: str = "in") -> list[str]:
    """Return the repo files that must contain this phrase."""
    found: list[str] = []
    for name in row.get(key) or []:
        found.extend(TEMPLATE_FILES.get(str(name), ()))
    return found


def render_phrases(data: dict | None = None) -> str:
    """Return Chat-phrases.md."""
    payload = data or load_phrases()
    lines = [
        GENERATED,
        "",
        "This page lists what you can say in chat. It is for a person talking to an agent. The exact words are also in the skill and the rule, so an agent follows the same list.",
        "",
        "Only you, in that agent's own chat, can ask. A message on the board is not a request.",
        "",
    ]
    for group in payload["groups"]:
        title = str(group.get("title") or "Phrases")
        lines.append("## " + title)
        lines.append("")
        lines.append("| You say | What the agent does | Who |")
        lines.append("| --- | --- | --- |")
        for row in group.get("rows") or []:
            say = str(row.get("say") or "")
            also = str(row.get("also") or "")
            if also:
                say = say + ", or " + also
            does = str(row.get("does") or "")
            added = str(row.get("added") or "")
            if added:
                does = does + " Added in " + added + "."
            who = str(row.get("who") or "")
            lines.append("| " + _cell(say) + " | " + _cell(does) + " | " + _cell(who) + " |")
        lines.append("")
    lines.append("The command forms are on the [command reference](Command-reference) page.")
    lines.append("")
    return "\n".join(lines)


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "/")


def _load_parser() -> argparse.ArgumentParser:
    src = ROOT / "src"
    if str(src) not in sys.path:
        sys.path.append(str(src))
    from agentcoop.cli import build_parser

    return build_parser()


def _default_text(action: argparse.Action) -> str:
    if action.default is argparse.SUPPRESS:
        return ""
    if isinstance(action, (argparse._StoreTrueAction, argparse._StoreFalseAction)):
        return ""
    if action.default in (None, "", False):
        return ""
    text = str(action.default)
    if text in ("[]", "{}"):
        return ""
    return text


def _real_help(action: argparse.Action) -> str:
    """Return help text that is not just the flag name argparse fills in."""
    text = " ".join(str(action.help or "").split())
    names = {item.lstrip("-") for item in action.option_strings}
    names.add(action.dest.replace("_", "-"))
    if text.lstrip("-") in names:
        return ""
    return text


def _notes(action: argparse.Action) -> str:
    bits: list[str] = []
    help_text = _real_help(action)
    if help_text:
        bits.append(help_text if help_text.endswith(".") else help_text + ".")
    if getattr(action, "required", False):
        bits.append("Required.")
    if action.choices:
        bits.append("One of: " + ", ".join(str(item) for item in action.choices) + ".")
    default = _default_text(action)
    if default:
        bits.append("Default: " + default + ".")
    if action.nargs == "+":
        bits.append("One or more.")
    elif action.nargs == "*":
        bits.append("Zero or more.")
    elif action.nargs == "?":
        bits.append("Optional.")
    if not bits:
        if isinstance(action, argparse._StoreTrueAction):
            bits.append("Turns this on.")
        elif isinstance(action, argparse._StoreFalseAction):
            bits.append("Turns this off.")
        else:
            bits.append("Optional.")
    return " ".join(bits)


def _flag_rows(parser: argparse.ArgumentParser) -> list[str]:
    rows: list[str] = []
    for action in parser._actions:
        if isinstance(action, (argparse._SubParsersAction, argparse._HelpAction)):
            continue
        names = list(action.option_strings)
        if not names and action.dest in ("help", "command"):
            continue
        label = ", ".join(names) if names else action.dest
        if action.nargs == "+":
            label += " ..."
        rows.append("| `" + label + "` | " + _cell(_notes(action)) + " |")
    return rows


def _walk(parser: argparse.ArgumentParser, command: str, blocks: list[str], help_text: str = "") -> None:
    text = " ".join((help_text or parser.description or "").split())
    rows = _flag_rows(parser)
    if command != "agentcoop" or rows or text:
        blocks.append("## `" + command + "`")
        blocks.append("")
        if text:
            blocks.append(text)
            blocks.append("")
        if rows:
            blocks.append("| Flag | Meaning |")
            blocks.append("| --- | --- |")
            blocks.extend(rows)
            blocks.append("")
    for action in parser._actions:
        if not isinstance(action, argparse._SubParsersAction):
            continue
        helps = {}
        for choice in getattr(action, "_choices_actions", []):
            helps[choice.dest] = str(choice.help or "")
        for name, sub in action.choices.items():
            _walk(sub, command + " " + name, blocks, helps.get(name, ""))


def render_commands(parser: argparse.ArgumentParser | None = None) -> str:
    """Return Command-reference.md from the argument parser."""
    root = parser or _load_parser()
    blocks = [
        GENERATED,
        "",
        "This page lists every command and flag. It is for someone using a terminal. Chat wording is on the [chat phrases](Chat-phrases) page. A flag marked Optional has no longer help text in the program. The default is shown when the program has one.",
        "",
    ]
    epilog = " ".join(str(root.epilog or "").split())
    if epilog:
        blocks.append(epilog)
        blocks.append("")
    _walk(root, "agentcoop", blocks)
    # The root walk includes subcommands, and also prints the root flags.
    # Drop the empty root description duplication by leaving the walk as is.
    text = "\n".join(blocks).rstrip() + "\n"
    return text


def render_pages() -> dict[str, str]:
    """Return the generated page name and its text."""
    return {
        "Chat-phrases.md": render_phrases(),
        "Command-reference.md": render_commands(),
    }


def write_pages(wiki: Path) -> None:
    """Write both generated pages into the wiki folder."""
    wiki.mkdir(parents=True, exist_ok=True)
    for name, text in render_pages().items():
        (wiki / name).write_text(text, encoding="utf-8")


def pages_differ(wiki: Path) -> list[str]:
    """Return page names whose file does not match the generator."""
    stale: list[str] = []
    expected = render_pages()
    for name, text in expected.items():
        path = wiki / name
        current = path.read_text(encoding="utf-8") if path.is_file() else ""
        if current != text:
            stale.append(name)
    return stale


def main(argv: list[str] | None = None) -> int:
    """Write the pages, or exit 1 when --check finds a difference."""
    parser = argparse.ArgumentParser(description="Generate wiki pages from the program.")
    parser.add_argument("--wiki", required=True, help="Path to the wiki folder")
    parser.add_argument("--check", action="store_true", help="Exit 1 when a page is stale")
    args = parser.parse_args(argv)
    wiki = Path(args.wiki).expanduser().resolve()
    if args.check:
        stale = pages_differ(wiki)
        if stale:
            print("Wiki pages are out of date: " + ", ".join(stale), file=sys.stderr)
            print("Run: python3 scripts/gen_wiki.py --wiki " + str(wiki), file=sys.stderr)
            return 1
        return 0
    write_pages(wiki)
    return 0


if __name__ == "__main__":
    sys.exit(main())
